const { chromium } = require('playwright');
(async () => {
  const out = process.argv[2];
  const vw = +(process.argv[3] || 1100), vh = +(process.argv[4] || 760), tag = process.argv[5] || 'w';
  const b = await chromium.launch();
  const errs = [];
  const ctx = await b.newContext(vw < 600 ? { viewport: { width: vw, height: vh }, deviceScaleFactor: 2, hasTouch: true, isMobile: true } : { viewport: { width: vw, height: vh } });
  const p = await ctx.newPage();
  p.on('pageerror', e => errs.push('PAGEERR ' + e.message + ' ' + (e.stack || '').split('\n').slice(1, 3).join(' | ')));
  await p.goto('file://' + out + '/page.html#debug');
  await p.waitForTimeout(500);
  await p.evaluate(() => document.getElementById('startBtn').click());
  await p.evaluate(() => { __hg.inv(true); __hg.freeze(true); });
  const shot = async (name, fn, steps) => {
    await p.evaluate(([fn, steps]) => { if (fn) eval(fn); __hg.step(steps); }, [fn, steps]);
    await p.waitForTimeout(60);
    await p.screenshot({ path: `${out}/${tag}-${name}.png` });
  };
  await shot('march', '', 90);
  await shot('looks-hyper', "__hg.jump(5); __hg.step(200); __hg.attack('hypergamy')", 40);
  await shot('looks-needles-pills', "__hg.step(150); __hg.attack('needles'); __hg.attack('pills')", 35);
  await shot('looks-liver-ratings', "__hg.step(150); __hg.attack('liver'); __hg.attack('ratings')", 45);
  await shot('looks-ad-flood', "__hg.step(150); __hg.attack('courseAd'); __hg.attack('chatFlood')", 70);
  await shot('looks-bonesmash', "__hg.step(150); __hg.attack('bonesmash')", 40);
  await shot('looks-bonesmash-hit', '', 22);
  await shot('apol-axes', "__hg.jump(4); __hg.step(200); __hg.hurtBoss(200); __hg.step(5); __hg.attack('axes')", 30);
  await shot('apol-chop', "__hg.step(150); __hg.attack('axeChop')", 45);
  await shot('disp-link-fish', "__hg.jump(6); __hg.step(200); __hg.attack('missingLink'); __hg.attack('fishLegs')", 100);
  await shot('disp-fish-leap', '', 40);
  await shot('ceo-bars', "__hg.jump(2); __hg.step(200); __hg.attack('bars')", 75);
  await shot('queen-tele', "__hg.jump(3); __hg.step(200); __hg.setUpg('queen', 10); __hg.ready(); __hg.power('queen')", 50);
  await shot('queen-go', '', 8);
  await shot('queen-sweep', "__hg.harvest(2); __hg.step(300); __hg.event('flow'); __hg.step(5); __hg.setUpg('queen', 5); __hg.ready(); __hg.power('queen')", 40);
  await shot('swarm-in', "__hg.harvest(3); __hg.step(200); __hg.event('swarm')", 60);
  await shot('swarm-hover', '', 150);
  await shot('swarm-exit', '', 150);
  await shot('magnet', "__hg.setUpg('magnet', 10); __hg.power('magnet')", 20);
  await shot('crazy-intro', "__hg.crazy(0, 2)", 90);
  await shot('crazy-fight', '', 400);
  console.log(JSON.stringify(await p.evaluate(() => __hg.get().bosses)));
  console.log('ERRORS', JSON.stringify(errs, null, 1));
  await b.close();
})();
